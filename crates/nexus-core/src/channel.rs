// nexus-core: channel.rs
// Software repository channels configuration

#[derive(Debug, Clone, PartialEq, Eq)]
pub enum ChannelType {
    Main,
    Universe,
    Restricted,
    Multiverse,
    SourceCode,
    Custom(String),
}

impl ChannelType {
    pub fn as_str(&self) -> &str {
        match self {
            ChannelType::Main => "main",
            ChannelType::Universe => "universe",
            ChannelType::Restricted => "restricted",
            ChannelType::Multiverse => "multiverse",
            ChannelType::SourceCode => "source",
            ChannelType::Custom(s) => s.as_str(),
        }
    }
}

#[derive(Debug, Clone)]
pub struct RepoChannel {
    pub id: String,
    pub name: String,
    pub channel_type: ChannelType,
    pub description: String,
    pub enabled: bool,
    pub official: bool,
}

impl RepoChannel {
    pub fn new(id: &str, name: &str, channel_type: ChannelType, description: &str, enabled: bool, official: bool) -> Self {
        Self {
            id: id.to_string(),
            name: name.to_string(),
            channel_type,
            description: description.to_string(),
            enabled,
            official,
        }
    }

    pub fn toggle(&mut self) {
        self.enabled = !self.enabled;
    }
}

#[derive(Debug, Clone)]
pub struct ChannelManager {
    pub channels: Vec<RepoChannel>,
    pub main_server_url: String,
    pub active_server_url: String,
    pub cdrom_install_enabled: bool,
}

impl Default for ChannelManager {
    fn default() -> Self {
        Self::new()
    }
}

impl ChannelManager {
    pub fn new() -> Self {
        let channels = vec![
            RepoChannel::new(
                "main",
                "Canonical-supported free and open-source software (main)",
                ChannelType::Main,
                "Officially supported open-source system software audited by security teams.",
                true,
                true,
            ),
            RepoChannel::new(
                "universe",
                "Community-maintained free and open-source software (universe)",
                ChannelType::Universe,
                "Vast collection of community maintained software packages and tools.",
                true,
                true,
            ),
            RepoChannel::new(
                "restricted",
                "Proprietary drivers for devices (restricted)",
                ChannelType::Restricted,
                "Binary drivers for graphics cards, Wi-Fi adapters, and microcode.",
                true,
                true,
            ),
            RepoChannel::new(
                "multiverse",
                "Software restricted by copyright or legal issues (multiverse)",
                ChannelType::Multiverse,
                "Media codecs, patent-encumbered algorithms, and commercial plugins.",
                false,
                true,
            ),
            RepoChannel::new(
                "source",
                "Source code",
                ChannelType::SourceCode,
                "Enable deb-src repositories to download source code for compilation.",
                false,
                true,
            ),
        ];

        Self {
            channels,
            main_server_url: "https://archive.ubuntu.com/ubuntu/".to_string(),
            active_server_url: "https://archive.ubuntu.com/ubuntu/".to_string(),
            cdrom_install_enabled: false,
        }
    }

    pub fn is_channel_enabled(&self, id: &str) -> bool {
        self.channels.iter().find(|c| c.id == id).map_or(false, |c| c.enabled)
    }

    pub fn set_channel_enabled(&mut self, id: &str, enabled: bool) -> bool {
        if let Some(ch) = self.channels.iter_mut().find(|c| c.id == id) {
            ch.enabled = enabled;
            true
        } else {
            false
        }
    }

    pub fn toggle_channel(&mut self, id: &str) -> bool {
        if let Some(ch) = self.channels.iter_mut().find(|c| c.id == id) {
            ch.toggle();
            true
        } else {
            false
        }
    }

    pub fn set_active_server(&mut self, url: &str) {
        self.active_server_url = url.to_string();
    }

    pub fn export_sources_list(&self) -> String {
        let mut out = String::new();
        out.push_str("# Generated by Nexus Software & Updates\n");
        let active_components: Vec<&str> = self
            .channels
            .iter()
            .filter(|c| c.enabled && c.channel_type != ChannelType::SourceCode)
            .map(|c| c.channel_type.as_str())
            .collect();

        if !active_components.is_empty() {
            out.push_str(&format!(
                "deb {} noble {}\n",
                self.active_server_url,
                active_components.join(" ")
            ));
            out.push_str(&format!(
                "deb {} noble-updates {}\n",
                self.active_server_url,
                active_components.join(" ")
            ));
            out.push_str(&format!(
                "deb {} noble-security {}\n",
                self.active_server_url,
                active_components.join(" ")
            ));
        }

        if self.is_channel_enabled("source") && !active_components.is_empty() {
            out.push_str(&format!(
                "deb-src {} noble {}\n",
                self.active_server_url,
                active_components.join(" ")
            ));
        }

        out
    }
}
